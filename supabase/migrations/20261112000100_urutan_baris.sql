-- Urutan baris = urutan insert, seperti urutan baris di Google Sheets dulu.
-- Beberapa tampilan (mis. daftar kategori) mengikuti urutan ini, dan Postgres tidak menjamin urutan tanpa ORDER BY.
-- Kolom ini tidak ada di server/db/schema.ts dan tidak pernah ditulis aplikasi; nilainya diisi identity.

do $$
declare t text;
begin
  for t in select tablename from pg_tables where schemaname = 'public' loop
    execute format('alter table public.%I add column if not exists no bigint generated by default as identity', t);
  end loop;
end $$;
